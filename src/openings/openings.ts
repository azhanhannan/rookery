// Opening names and Book detection from lichess-org/chess-openings (CC0; see the header of openings.tsv).
// The data is loaded on first use into its own chunk, so it never weighs on the main bundle.
//
// Book positions are every position on a named line, not only the named end positions: a move along a
// known line is theory even where the dataset gives that position no name of its own.
import { DEFAULT_POSITION } from 'chess.js';
import type { BookInfo } from '../review/types';

export type Opening = { eco: string; name: string };

/** EPD -> opening; null for a book position that has no name of its own. */
type Index = Map<string, Opening | null>;

let index: Index | null = null;
let loading: Promise<Index> | null = null;

/** Loads and indexes the dataset once; later calls return the same promise. A failed load is retried next time. */
export function loadOpenings(): Promise<void> {
  if (!loading) {
    loading = import('./positions.tsv?raw').then(
      (mod) => (index = parseIndex(mod.default)),
      (err: unknown) => {
        loading = null;
        throw err;
      },
    );
  }
  return loading.then(() => undefined);
}

/** positions.tsv rows: `epd`, or `epd<TAB>eco<TAB>name` (generated by scripts/build-openings.mjs). */
export function parseIndex(text: string): Index {
  const map: Index = new Map();
  for (const row of text.split(/\r?\n/)) {
    if (!row) continue;
    const [key, eco, name] = row.split('\t');
    map.set(key, eco ? { eco, name } : null);
  }
  return map;
}

/**
 * First four FEN fields: placement, side to move, castling, en passant. The dataset was keyed with
 * chess.js FENs, which name an en-passant square only when a capture is legal; a FEN that names it
 * regardless is matched by `find` retrying without it.
 */
export function toEpd(fen: string): string {
  return fen.trim().split(/\s+/).slice(0, 4).join(' ');
}

const START_EPD = toEpd(DEFAULT_POSITION);

function find(fen: string): Opening | null | undefined {
  if (!index) throw new Error('Openings not loaded: await loadOpenings() first');
  const key = toEpd(fen);
  const hit = index.get(key);
  if (hit !== undefined || key.endsWith(' -')) return hit;
  return index.get(key.replace(/ \S+$/, ' -'));
}

/** Sync, after `loadOpenings()`: the opening named at exactly this position, if any. */
export function openingAt(fen: string): Opening | undefined {
  return find(fen) ?? undefined;
}

/** Sync, after `loadOpenings()`: whether this position lies on a named line. */
export function isBookPosition(fen: string): boolean {
  return find(fen) !== undefined;
}

/**
 * Book facts for a game (SPEC "Book" label): the leading plies whose positions are all in the dataset,
 * and the deepest named opening among them. Only games from the standard start position have a book.
 */
export async function lookupBook(startFen: string, moves: { fenAfter: string }[]): Promise<BookInfo> {
  if (toEpd(startFen) !== START_EPD) return { bookPlies: 0 };
  await loadOpenings();
  const info: BookInfo = { bookPlies: 0 };
  for (const move of moves) {
    const hit = find(move.fenAfter);
    if (hit === undefined) break;
    info.bookPlies++;
    if (hit) {
      info.eco = hit.eco;
      info.name = hit.name;
    }
  }
  return info;
}
